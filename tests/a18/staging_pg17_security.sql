DO $check$
BEGIN
  IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.alert_preferences'::regclass)
   OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.user_notifications'::regclass)
  THEN RAISE EXCEPTION 'Both new tables must enable RLS'; END IF;

  IF has_table_privilege('anon','public.user_notifications','SELECT')
   OR has_table_privilege('anon','public.alert_preferences','SELECT')
   OR has_table_privilege('authenticated','public.user_notifications','SELECT')
   OR has_table_privilege('authenticated','public.user_notifications','INSERT')
   OR has_table_privilege('authenticated','public.user_notifications','DELETE')
   OR has_table_privilege('authenticated','public.user_notifications','TRUNCATE')
  THEN RAISE EXCEPTION 'Broad table grants survived revocation'; END IF;

  IF has_column_privilege('authenticated','public.user_notifications','event_key','SELECT')
   OR has_column_privilege('authenticated','public.user_notifications','user_id','SELECT')
   OR has_column_privilege('authenticated','public.user_notifications','event_key','UPDATE')
   OR has_column_privilege('authenticated','public.user_notifications','opportunity_id','UPDATE')
   OR has_column_privilege('authenticated','public.alert_preferences','updated_at','UPDATE')
   OR has_column_privilege('authenticated','public.alert_preferences','updated_at','INSERT')
  THEN RAISE EXCEPTION 'Unexpected metadata or timestamp privileges'; END IF;

  IF NOT has_column_privilege('authenticated','public.user_notifications','id','SELECT')
    OR NOT has_column_privilege('authenticated','public.user_notifications','read_at','UPDATE')
    OR NOT has_column_privilege('authenticated','public.user_notifications','dismissed_at','UPDATE')
  THEN RAISE EXCEPTION 'Missing required narrow client privileges'; END IF;
END $check$;

